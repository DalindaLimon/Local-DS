def _ffmpeg(args: list[str]) -> bool:
    proc = subprocess.run(["ffmpeg", "-y", "-hide_banner", "-loglevel", "error", *args], capture_output=True, text=True)
    if proc.returncode != 0:
        print("ffmpeg:", proc.stderr.strip()[-300:], file=sys.stderr)
    return proc.returncode == 0


def _image(path: Path, c0: str, c1: str, w: int = 640, hgt: int = 360) -> bool:
    if path.exists():
        return True
    ok = _ffmpeg(["-f", "lavfi", "-i", f"gradients=s={w}x{hgt}:c0={c0}:c1={c1}:x0=0:y0=0:x1={w}:y1={hgt}:d=1",
                  "-frames:v", "1", "-q:v", "4", str(path)])  # fmt: skip
    if not ok:
        ok = _ffmpeg(["-f", "lavfi", "-i", f"color=c={c0}:s={w}x{hgt}", "-frames:v", "1", str(path)])
    return ok


def _video(path: Path, seconds: int, hue: int) -> bool:
    return _ffmpeg([
        "-f", "lavfi", "-i", f"testsrc2=s=720x1280:r=30:d={seconds}",
        "-f", "lavfi", "-i", f"sine=frequency={220 + hue}:duration={seconds}",
        "-vf", f"hue=h={hue}", "-c:v", "libx264", "-preset", "veryfast", "-pix_fmt", "yuv420p",
        "-c:a", "aac", "-b:a", "96k", "-shortest", "-movflags", "+faststart", str(path),
    ])  # fmt: skip


def remove(s: Settings) -> None:
    conn = connect(s.db_path)
    ids = [r["id"] for r in conn.execute("SELECT id FROM sources WHERE kind='demo'")]
    with tx(conn):
        for sid in ids:
            for r in conn.execute("SELECT id, video_id FROM shorts WHERE source_id=?", (sid,)).fetchall():
                (s.videos_dir / f"{r['video_id']}.mp4").unlink(missing_ok=True)
                (s.thumbs_dir / f"{r['video_id']}.jpg").unlink(missing_ok=True)
                conn.execute("DELETE FROM comments WHERE item_type='short' AND item_id=?", (r["id"],))
                conn.execute("DELETE FROM reactions WHERE item_type='short' AND item_id=?", (r["id"],))
            conn.execute(
                "DELETE FROM comments WHERE item_type='item' AND item_id IN (SELECT id FROM items WHERE source_id=?)",
                (sid,),
            )
            conn.execute(
                "DELETE FROM reactions WHERE item_type='item' AND item_id IN (SELECT id FROM items WHERE source_id=?)",
                (sid,),
            )
            conn.execute("DELETE FROM shorts WHERE source_id=?", (sid,))
            conn.execute("DELETE FROM sources WHERE id=?", (sid,))
        # Demo accounts have publicly known passwords. Remove them unless their password was changed.
        users = conn.execute("SELECT id, username, pw_hash FROM users").fetchall()
        known = [
            u for u in users if u["username"] in DEMO_USERS and verify_password(u["pw_hash"], DEMO_USERS[u["username"]])
        ]
        for u in known:
            conn.execute("DELETE FROM users WHERE id=?", (u["id"],))
    print(f"removed {len(ids)} demo sources and {len(known)} demo user(s)")


def seed(s: Settings, with_users: bool = False, videos: bool = True) -> None:
    s.ensure_dirs()
    init_db(s.db_path)
    conn = connect(s.db_path)
    rng = random.Random(42)
    now = time.time()
    demo_dir = s.data_dir / "demo"
    demo_dir.mkdir(exist_ok=True)

    if with_users and conn.execute("SELECT COUNT(*) FROM users").fetchone()[0] == 0:
        conn.execute(
            "INSERT INTO users(username, pw_hash, is_admin, created_at) VALUES('demo', ?, 1, ?)",
            (hash_password(DEMO_USERS["demo"]), now),
        )
        conn.execute(
            "INSERT INTO users(username, pw_hash, is_admin, created_at) VALUES('friend', ?, 0, ?)",
            (hash_password(DEMO_USERS["friend"]), now),
        )
        print("created users demo/demo-password (admin) and friend/friend-password")
        print("these passwords are public: run `python -m app.seed --remove` before real use")

    if conn.execute("SELECT 1 FROM sources WHERE kind='demo'").fetchone():
        print("demo data already present (use --remove first to re-create)")
        return

    images = []
    for i in range(10):
        p = demo_dir / f"img{i}.jpg"
        if _image(p, COLORS[i % len(COLORS)], COLORS[(i + 3) % len(COLORS)]):
            images.append(f"/media/demo/{p.name}")

    with tx(conn):
        source_ids = []
        for title, topics in DEMO_SOURCES:
            cur = conn.execute(
                """INSERT INTO sources(kind, title, site_url, rss_enabled, shorts_enabled, topics, status,
                   last_fetched, created_at) VALUES('demo', ?, 'https://example.com/', 1, 1, ?, 'ok', ?, ?)""",
                (title, topics, now, now),
            )
            source_ids.append(cur.lastrowid)
        for n in range(60):
            sid = source_ids[n % len(source_ids)]
            title = TITLES[n % len(TITLES)] + ("" if n < len(TITLES) else f" (part {n // len(TITLES) + 1})")
            image = images[n % len(images)] if images and n % 3 != 2 else None
            body = f"<p>{LOREM}</p><p>{LOREM * 2}</p><ul><li>Point one</li><li>Point two</li></ul>"
            conn.execute(
                """INSERT INTO items(source_id, guid, url, title, author, excerpt, content_html, image_url,
                   published_at, fetched_at) VALUES(?,?,?,?,?,?,?,?,?,?)""",
                (sid, f"demo-{n}", f"https://example.com/post/{n}", title, "demo", LOREM, body, image,
                 now - n * 3600 * rng.uniform(0.5, 3), now),
            )  # fmt: skip

    if not videos:
        print("seeded demo posts (no videos)")
        return
    made = 0
    for i in range(DEMO_SHORTS + DEMO_EXPIRED):
        vid = f"demoShort{i:02d}"
        sid = source_ids[i % len(source_ids)]
        thumb = s.thumbs_dir / f"{vid}.jpg"
        expired = i >= DEMO_SHORTS
        if expired:
            _image(thumb, COLORS[i % len(COLORS)], "#111111", 360, 640)
            conn.execute(
                """INSERT INTO shorts(video_id, source_id, title, channel_name, url, published_at, downloaded_at,
                   expired_at, thumb_path, status, created_at) VALUES(?,?,?,?,?,?,?,?,?,'expired',?)""",
                (vid, sid, f"Expired demo Short #{i}", DEMO_SOURCES[i % 5][0], f"https://www.youtube.com/shorts/{vid}",
                 now - 12 * 86400, now - 10 * 86400, now - 3 * 86400 + i, thumb.name if thumb.exists() else None, now),
            )  # fmt: skip
            continue
        video = s.videos_dir / f"{vid}.mp4"
        if not video.exists() and not _video(video, 6, i * 40):
            continue
        _ffmpeg(["-ss", "1", "-i", str(video), "-frames:v", "1", "-vf", "scale=360:-2", str(thumb)])
        conn.execute(
            """INSERT INTO shorts(video_id, source_id, title, channel_name, url, published_at, downloaded_at,
               file_path, thumb_path, duration, width, height, status, created_at)
               VALUES(?,?,?,?,?,?,?,?,?,6,720,1280,'available',?)""",
            (vid, sid, f"Demo Short #{i}: swipe up for the next one", DEMO_SOURCES[i % 5][0],
             f"https://www.youtube.com/shorts/{vid}", now - i * 7200, now - i * 3600, video.name,
             thumb.name if thumb.exists() else None, now),
        )  # fmt: skip
        made += 1
    print(f"seeded {len(DEMO_SOURCES)} demo sources, 60 posts, {made} Shorts + {DEMO_EXPIRED} past Shorts")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--users", action="store_true", help="create demo users if the database has none")
    ap.add_argument("--remove", action="store_true", help="remove all demo data")
    ap.add_argument("--no-videos", action="store_true", help="skip generating demo videos")
    args = ap.parse_args()
    s = load_settings()
    if args.remove:
        remove(s)
    else:
        seed(s, with_users=args.users, videos=not args.no_videos)


if __name__ == "__main__":
    main()
